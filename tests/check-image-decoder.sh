#!/bin/sh
# Invariant: the image decoder (src/client/refresh/files/imgdecode.c,
# decision docs/decisions/0010-imageio-decoder.md) decodes PNG, JPEG and
# TGA only, and refuses everything else before decoding it. PNG and TGA
# decode to the straight-alpha RGBA bytes stb_image returned (a 16-bit
# TGA to within one level); JPEG not byte for byte: the JPEG IDCT and
# the chroma upsampling differ from stb_image's by up to tens of levels
# at edges (the stock rerelease JPEGs differ by up to 56 levels, and
# 11.8% of their colour bytes differ). Refused, where stb_image decoded them: CMYK and YCCK
# JPEGs, a palette index past the palette, a colour-mapped TGA whose map
# is not 24-bit, a 15-bit TGA, a truecolour TGA that carries a colour
# map, a colour-mapped TGA (types 1 and 9) with a 24-bit map whose first
# entry index is not 0, a colour-mapped TGA with 16-bit indices, a type 2
# TGA with 8-bit pixels, more than 2^26 pixels, a JPEG cut inside its scan data and a
# run-length TGA cut inside a run. Decoded, where stb_image refused it,
# and kept in the host test as a known gap: a PNG whose complete zlib
# stream holds fewer rows than it declares, for which ImageIO's status
# stays complete.
#
# (a) Always: tests/image/imgdecode_test.c is compiled with the system
#     compiler against imgdecode.c alone, with ASAN and UBSAN when the
#     compiler has them, and run. Every file is generated by the test; no
#     engine, no SDL, no game data. On Darwin it links ImageIO,
#     CoreGraphics and CoreFoundation and decodes; elsewhere it checks the
#     pure functions and that there is no decoder. Two more host tests
#     run with the same flags: tests/image/skyorder_test.c, the sky face
#     order and the stock size (files/skyorder.h, pure functions), and
#     tests/image/skyload_test.c, the real files/image.c against a stub
#     filesystem, decoder and load_image: which sky file is loaded, the
#     asset size handed on, and the wall texture order unchanged.
# (b) On Darwin with leaks(1): a build without the sanitizers decodes
#     every case, the refusals included, 20 times under
#     "leaks --atExit", which must report 0 leaks. Without leaks(1) one
#     line "check-image-decoder: leaks skipped: <reason>".
#
# Both runs have a wall bound of IMGDEC_CHECK_SECONDS (default 300). A
# watchdog kills the run it started once the bound has passed, and the
# check fails with "<run> outlived its <n> s bound". Under leaks(1) the
# test also ends itself at the bound (--bound), because a killed leaks(1)
# leaves the process it runs behind.
set -eu
cd "$(dirname "$0")/.."

tmp=$(mktemp -d "${TMPDIR:-/tmp}/image-decoder.XXXXXX")
trap 'rm -rf "${tmp:?}"' EXIT

bound=${IMGDEC_CHECK_SECONDS:-300}
case $bound in
	'' | *[!0-9]*)
		echo "check-image-decoder: IMGDEC_CHECK_SECONDS is not a whole number of seconds"
		exit 1
		;;
esac
if [ "$bound" -lt 1 ]; then
	echo "check-image-decoder: IMGDEC_CHECK_SECONDS is 0"
	exit 1
fi

# bounded <command...>: runs the command under a watchdog and returns its
# status. Once the bound has passed, the watchdog writes ${tmp}/expired
# and kills the command's PID, and nothing else. The watchdog sleeps in
# one-second steps, so when it is killed early no sleep outlives it.
bounded()
{
	"$@" &
	run=$!
	(
		n=0
		while [ "$n" -lt "$bound" ]; do
			sleep 1
			n=$((n + 1))
		done
		if kill -0 "$run" 2>/dev/null; then
			: > "${tmp:?}/expired"
			kill "$run" 2>/dev/null
		fi
	) < /dev/null > /dev/null 2>&1 &
	dog=$!
	rc=0
	wait "$run" || rc=$?
	kill "$dog" 2>/dev/null || :
	wait "$dog" 2>/dev/null || :
	return "$rc"
}

# expired <run>: fails the check when the watchdog killed the run
expired()
{
	if [ -e "${tmp:?}/expired" ]; then
		echo "check-image-decoder: $1 outlived its $bound s bound and was killed"
		exit 1
	fi
}

cc=${CC:-cc}
flags="-std=gnu99 -Wall -Wextra -Werror -g -O1 -fno-strict-aliasing -fwrapv"
san="-fsanitize=address,undefined -fno-sanitize-recover=undefined -fno-omit-frame-pointer"
libs=""
if [ "$(uname -s)" = Darwin ]; then
	libs="-framework ImageIO -framework CoreGraphics -framework CoreFoundation"
fi
srcs="src/client/refresh/files/imgdecode.c tests/image/imgdecode_test.c"

# (a) the host test, with sanitizers when this compiler can build and run with them
printf 'int main(void){return 0;}\n' > "${tmp:?}/probe.c"
sflags=$flags
# shellcheck disable=SC2086 # san is a word list
if $cc $san -o "${tmp:?}/probe" "${tmp:?}/probe.c" >/dev/null 2>&1 && "${tmp:?}/probe" >/dev/null 2>&1; then
	sflags="$flags $san"
else
	echo "check-image-decoder: $cc cannot build with ASAN and UBSAN; running without them"
fi

# shellcheck disable=SC2086 # sflags, srcs and libs are word lists
if ! $cc $sflags -o "${tmp:?}/imgdecode_test" $srcs $libs > "${tmp:?}/cc.out" 2>&1; then
	cat "${tmp:?}/cc.out"
	echo "check-image-decoder: the host test does not build"
	exit 1
fi

# the sky face order: pure functions in a header, no decoder needed
# shellcheck disable=SC2086 # sflags is a word list
if ! $cc $sflags -o "${tmp:?}/skyorder_test" tests/image/skyorder_test.c > "${tmp:?}/cc.out" 2>&1; then
	cat "${tmp:?}/cc.out"
	echo "check-image-decoder: the sky order test does not build"
	exit 1
fi
status=0
bounded "${tmp:?}/skyorder_test" || status=$?
expired "the sky order test"
if [ "$status" -ne 0 ]; then
	echo "check-image-decoder: the sky order test failed"
	exit 1
fi

# the sky face loader: the real image.c against a stub filesystem and decoder
# (image.c has an old sign-compare warning, so -Wno-sign-compare)
# shellcheck disable=SC2086 # sflags is a word list
if ! $cc $sflags -Wno-sign-compare -DYQ2OSTYPE=\"test\" -DYQ2ARCH=\"test\" -I. \
	-o "${tmp:?}/skyload_test" tests/image/skyload_test.c \
	src/client/refresh/files/image.c > "${tmp:?}/cc.out" 2>&1; then
	cat "${tmp:?}/cc.out"
	echo "check-image-decoder: the sky load test does not build"
	exit 1
fi
status=0
bounded "${tmp:?}/skyload_test" || status=$?
expired "the sky load test"
if [ "$status" -ne 0 ]; then
	echo "check-image-decoder: the sky load test failed"
	exit 1
fi

status=0
bounded "${tmp:?}/imgdecode_test" || status=$?
expired "the host test"
if [ "$status" -ne 0 ]; then
	echo "check-image-decoder: the host test failed"
	exit 1
fi

# (b) no leak on any path, refusals included
if [ "$(uname -s)" != Darwin ]; then
	[ "${CHECK_IMAGE_DECODER_REQUIRE:-0}" != 1 ] || { echo "check-image-decoder: CHECK_IMAGE_DECODER_REQUIRE=1 and the leak run cannot run: not Darwin"; exit 1; }
	echo "check-image-decoder: leaks skipped: not Darwin"
elif ! command -v leaks >/dev/null 2>&1; then
	[ "${CHECK_IMAGE_DECODER_REQUIRE:-0}" != 1 ] || { echo "check-image-decoder: CHECK_IMAGE_DECODER_REQUIRE=1 and the leak run cannot run: no leaks(1)"; exit 1; }
	echo "check-image-decoder: leaks skipped: no leaks(1)"
else
	# shellcheck disable=SC2086 # flags, srcs and libs are word lists
	if ! $cc $flags -o "${tmp:?}/imgdecode_plain" $srcs $libs > "${tmp:?}/cc.out" 2>&1; then
		cat "${tmp:?}/cc.out"
		echo "check-image-decoder: the leak build does not build"
		exit 1
	fi
	status=0
	bounded env MallocStackLogging=1 leaks --atExit -- "${tmp:?}/imgdecode_plain" \
		--bound "$bound" --loop 20 > "${tmp:?}/leaks.out" 2>&1 || status=$?
	if [ -e "${tmp:?}/expired" ]; then
		cat "${tmp:?}/leaks.out"
	fi
	expired "leaks(1)"
	# leaks(1) exits 0 whatever the test's own status: the test's last line
	# must show every loop run with no failure
	if [ "$status" -ne 0 ] || ! grep -q ' 0 leaks for 0 total leaked bytes' "${tmp:?}/leaks.out" ||
		! grep -Eq '^imgdecode_test: 20 loops of [0-9]+ cases, [0-9]+ checks, 0 failed$' "${tmp:?}/leaks.out"; then
		cat "${tmp:?}/leaks.out"
		echo "check-image-decoder: leaks found, the test failed or ended early, or leaks(1) failed (status $status)"
		exit 1
	fi
	grep -E '^imgdecode_test:| leaks for ' "${tmp:?}/leaks.out"
fi

echo "check-image-decoder: ok"
